-- Usuarios
CREATE TABLE USERS (
    id_user NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(255) UNIQUE NOT NULL,
    password VARCHAR2(255) NOT NULL,
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Autos
CREATE TABLE CARS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR2(100) NOT NULL,                          
    model VARCHAR2(100) NOT NULL,                          
    year NUMBER(4) NOT NULL CHECK (year >= 1886),          
    cost NUMBER(10, 2) NOT NULL CHECK (cost > 0),          
    stock NUMBER NOT NULL CHECK (stock >= 0),              
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP         
);

-- Clientes
CREATE TABLE CLIENTS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(255) NOT NULL,
    email VARCHAR2(255) UNIQUE NOT NULL,
    phone_number VARCHAR2(20) NOT NULL,
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    cars_purchased NUMBER DEFAULT 0 NOT NULL,
    total_spent NUMBER(10, 2) DEFAULT 0 NOT NULL
);

-- Ventas
CREATE TABLE SALES (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    car_id NUMBER NOT NULL,
    sale_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    total_price NUMBER(10, 2) NOT NULL,
    FOREIGN KEY (client_id) REFERENCES CLIENTS (id) ON DELETE CASCADE,
    FOREIGN KEY (car_id) REFERENCES CARS (id) ON DELETE CASCADE
);

